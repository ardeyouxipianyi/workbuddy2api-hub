_lock = threading.Lock()
_file_cache = {"key": None, "data": None}


def _candidate_file():
    """The out-of-band snapshot path, or None when none is configured."""
    env = os.environ.get("WB_PRICING_FILE")
    if env:
        return env
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "pricing", "pricing.json")
    return path if os.path.isfile(path) else None


def load_pricing():
    """The active pricing snapshot, reloaded when the file changes.

    The file (when present) wins over the inline copy so an operator can
    drop a refreshed snapshot next to the script without rebuilding; the
    inline copy keeps a broken or missing file from taking pricing down.
    """
    path = _candidate_file()
    key = ("inline", 0)
    if path:
        try:
            key = (path, os.path.getmtime(path))
        except OSError:
            path = None
            key = ("inline", 0)
    with _lock:
        if _file_cache["key"] == key and _file_cache["data"] is not None:
            return _file_cache["data"]
    data = None
    if path:
        try:
            with open(path, encoding="utf-8") as fh:
                loaded = json.load(fh)
            if isinstance(loaded, dict) and isinstance(loaded.get("models"), dict):
                data = loaded
        except Exception:
            data = None
    if data is None:
        data = _INLINE
    with _lock:
        _file_cache.update({"key": key, "data": data})
    return data


def _as_float(value, default=0.0):
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


_WEEKDAYS = ("mon", "tue", "wed", "thu", "fri", "sat", "sun")


def _utc_parts(epoch_sec):
    """(weekday, HHMM) at UTC, the timezone the source states its bands in.

    The gateway can run in a container on UTC and the panel is opened from
    any timezone, so the lookup must not depend on the host clock's zone.
    """
    t = time.gmtime(_as_float(epoch_sec))
    return _WEEKDAYS[t.tm_wday], t.tm_hour * 100 + t.tm_min


def _band_applies(band, prompt_tokens, day, hhmm):
    """Whether a band's condition holds for this row.

    A band carries one of two conditions - a minimum input length, or a UTC
    window; the source never mixes the two within one entry.
    """
    threshold = band.get("min_prompt_tokens")
    if threshold is not None:
        return prompt_tokens >= _as_float(threshold)
    days = band.get("days")
    if days and day not in days:
        return False
    start = _as_float(band.get("start"))
    end = _as_float(band.get("end")) or 2400.0
    return start <= hhmm < end


def band_for(entry, epoch_sec, prompt_tokens=0.0):
    """The rate table for this row, with the band index it came from.

    OpenRouter prices some models conditionally: a dearer rate once the input
    passes a length threshold, or a rate that depends on UTC time of day. The
    bands are kept in the source's order and the *last* one that applies wins.
    The source lists length bands in ascending threshold order, so taking the
    last match picks the tightest one instead of the first that happens to
    fit; the window bands do not overlap, so the same rule holds for them.

    A model without bands, or a row that satisfies none of them, falls back to
    the model's own flat price - the estimate degrades to the single-price
    behaviour rather than to zero. The index is None when that happened.
    """
    bands = entry.get("bands")
    if isinstance(bands, list) and bands:
        day, hhmm = _utc_parts(epoch_sec)
        hit = None
        for index, band in enumerate(bands):
            if not isinstance(band, dict):
                continue
            if not _band_applies(band, prompt_tokens, day, hhmm):
                continue
            table = band.get("flat")
            if isinstance(table, dict):
                hit = (table, index)
        if hit:
            return hit
    table = entry.get("flat")
    return (table if isinstance(table, dict) else {}), None


def _rate_for(entry, epoch_sec, prompt_tokens, meta):
    """The rate table for this row, its band index, and the CNY factor."""
    table, band = band_for(entry, epoch_sec, prompt_tokens)
    factor = 1.0
    if str(entry.get("currency") or "").upper() == "USD":
        factor = _as_float(meta.get("usd_cny"), 1.0) or 1.0
    return table, band, factor


def _pick(rate, key, fallback=None):
    """A per-million rate, falling back to a conservative neighbour.

    A row without a cache-hit price is billed at the miss price (never
    cheaper than the reference engine), so the estimate cannot understate
    the cost.
    """
    value = rate.get(key)
    if value is None and fallback:
        value = rate.get(fallback)
    return _as_float(value)


def compute_row(row, pricing=None):
    """The estimated cost of one usage row, in CNY.

    Returns {"cny": float, "known": bool, "band": int|None}. known=False
    means the model has no price entry - cny stays 0 and the caller reports
    it as unpriced instead of guessing. band is the time-of-day band the
    row's timestamp landed in (None for the model's flat price), so callers
    can tell a time-priced row from an ordinary one.
    """
    if not row:
        return {"cny": 0.0, "known": False, "band": None}
    pricing = pricing if pricing is not None else load_pricing()
    entry = (pricing.get("models") or {}).get(row.get("model"))
    if not isinstance(entry, dict):
        return {"cny": 0.0, "known": False, "band": None}
    meta = pricing.get("meta") or {}
    unit = _as_float(entry.get("unit")) or 1000000.0
    prompt = _as_float(row.get("prompt_tokens"))
    rate, band, factor = _rate_for(entry, row.get("at"), prompt, meta)
    cached = min(_as_float(row.get("cached_tokens")), prompt)
    uncached = prompt - cached
    # The output rate applies to completion_tokens alone: the upstream counts
    # the reasoning tokens inside completion (verified on live and logged rows,
    # see tests/_test_pricing.py), and so does this gateway when it has to
    # estimate a missing usage block. Billing reasoning_tokens on top would
    # charge them twice.
    output = _as_float(row.get("completion_tokens"))
    miss = _pick(rate, "input_cache_miss")
    hit = _pick(rate, "input_cache_hit", "input_cache_miss")
    out_rate = _pick(rate, "output")
    cny = (uncached * miss + cached * hit + output * out_rate) / unit * factor
    return {"cny": cny, "known": True, "band": band}


def sum_rows(rows, pricing=None):
    """Batch totals: {"cny", "priced", "missing"}.

    `missing` is model id -> occurrence count for rows the snapshot cannot
    price, so the panel can point at what is not covered instead of quietly
    under-reporting.
    """
    pricing = pricing if pricing is not None else load_pricing()
    total = 0.0
    priced = 0
    missing = {}
    for row in rows or []:
        cost = compute_row(row, pricing=pricing)
        if cost["known"]:
            total += cost["cny"]
            priced += 1
        else:
            mid = str((row or {}).get("model") or "")
            missing[mid] = missing.get(mid, 0) + 1
    return {"cny": total, "priced": priced, "missing": missing}


def usd_cny():
    """The snapshot's CNY-per-USD rate, for callers that show USD."""
    try:
        return float((load_pricing().get("meta") or {}).get("usd_cny") or 1.0)
    except (TypeError, ValueError):
        return 1.0


